function stepAt(t) {
  let idx = 0;
  for (let i = 0; i < CHAPTERS.length; i++) if (t >= CHAPTERS[i][0]) idx = i;
  const t0 = CHAPTERS[idx][0];
  const t1 = idx + 1 < CHAPTERS.length ? CHAPTERS[idx + 1][0] : DURATION;
  return { idx, t0, t1, progress: clamp((t - t0) / Math.max(0.001, t1 - t0), 0, 1) };
}

/* ---------------- 段内插值 ---------------- */
function shotAt(t) {
  let s = SHOTS[0];
  for (const sh of SHOTS) { if (t >= sh.t0) s = sh; }
  const k = clamp((t - s.t0) / (s.t1 - s.t0), 0, 1);
  const e = easeInOut(k);
  return {
    px: lerp(s.p0.x, s.p1.x, e), py: lerp(s.p0.y, s.p1.y, e), pz: lerp(s.p0.z, s.p1.z, e),
    lx: lerp(s.l0.x, s.l1.x, e), ly: lerp(s.l0.y, s.l1.y, e), lz: lerp(s.l0.z, s.l1.z, e),
    fov: lerp(s.f0, s.f1, e),
  };
}

function subAt(t) {
  for (const [a, b, s] of SUBS) if (t >= a && t < b) return s;
  return '';
}

